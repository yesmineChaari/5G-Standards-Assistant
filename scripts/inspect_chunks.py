"""Chunk statistics and random samples.

Usage:
    python scripts/inspect_chunks.py [--n 10] [--seed 42]

Prints chunk counts per spec, token-length statistics (min / median / p95 / max), a histogram,
the number of table and merged chunks, and N random chunks. Writes:
  * eval/results/chunk_stats.md    statistics (used in the slides)
  * eval/results/chunk_samples.md  the random chunks, for manual review
"""

from __future__ import annotations

import argparse
import random
import statistics
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.config import load_config, resolve_path  # noqa: E402
from src.ingest.chunker import load_chunks  # noqa: E402

BINS = [0, 40, 100, 200, 300, 400, 450, 600, 800]


def percentile(values: list[int], p: float) -> int:
    """Nearest-rank percentile."""
    s = sorted(values)
    k = max(0, min(len(s) - 1, round(p / 100 * len(s) + 0.5) - 1))
    return s[k]


def describe(values: list[int]) -> dict[str, Any]:
    return {
        "count": len(values),
        "min": min(values),
        "median": int(statistics.median(values)),
        "p95": percentile(values, 95),
        "max": max(values),
        "mean": round(statistics.mean(values), 1),
    }


def histogram(values: list[int]) -> list[tuple[str, int]]:
    out = []
    edges = BINS + [10**9]
    for lo, hi in zip(edges[:-1], edges[1:]):
        label = f"{lo}-{hi - 1}" if hi < 10**9 else f">={lo}"
        out.append((label, sum(1 for v in values if lo <= v < hi)))
    return out


def build_stats(chunks: list[dict[str, Any]], cfg: dict[str, Any]) -> str:
    c = cfg["chunking"]
    lines = [
        "# Chunk statistics",
        "",
        f"Generated by `scripts/inspect_chunks.py` from `{cfg['paths']['chunks_file']}`.",
        f"Chunking: structural (one chunk per section) with recursive fallback; "
        f"max_tokens={c['max_tokens']}, overlap_tokens={c['overlap_tokens']}, "
        f"min_tokens={c['min_tokens']}, max_table_tokens={c['max_table_tokens']}, "
        f"tokenizer={c.get('tokenizer', 'cl100k_base')}.",
        "",
        "## Counts",
        "",
        "| Spec | Sections with chunks | Chunks | Text chunks | Table chunks | Merged-section chunks |",
        "|---|---|---|---|---|---|",
    ]
    specs = sorted({ch["spec"] for ch in chunks})
    for spec in specs + ["All"]:
        xs = chunks if spec == "All" else [ch for ch in chunks if ch["spec"] == spec]
        n_sec = len({(ch["spec"], ch["section"]) for ch in xs})
        types = Counter(ch["chunk_type"] for ch in xs)
        merged = sum(1 for ch in xs if ch["merged_sections"])
        lines.append(
            f"| {spec} | {n_sec} | {len(xs)} | {types.get('text', 0)} | {types.get('table', 0)} | {merged} |"
        )

    lines += [
        "",
        "## Token lengths (chunk text, without the header line)",
        "",
        "| Subset | Count | Min | Median | p95 | Max | Mean |",
        "|---|---|---|---|---|---|---|",
    ]
    subsets = [(s, [ch for ch in chunks if ch["spec"] == s]) for s in specs]
    subsets += [
        ("text chunks", [ch for ch in chunks if ch["chunk_type"] == "text"]),
        ("table chunks", [ch for ch in chunks if ch["chunk_type"] == "table"]),
        ("all", chunks),
    ]
    for name, xs in subsets:
        d = describe([ch["n_tokens"] for ch in xs])
        lines.append(
            f"| {name} | {d['count']} | {d['min']} | {d['median']} | {d['p95']} | {d['max']} | {d['mean']} |"
        )

    lines += ["", "## Histogram (all chunks)", "", "| Tokens | Chunks | |", "|---|---|---|"]
    hist = histogram([ch["n_tokens"] for ch in chunks])
    top = max(n for _, n in hist) or 1
    for label, n in hist:
        lines.append(f"| {label} | {n} | {'#' * round(40 * n / top)} |")

    small = sum(1 for ch in chunks if ch["n_tokens"] < c["min_tokens"])
    lines += [
        "",
        f"Chunks below min_tokens ({c['min_tokens']}): {small} "
        "(short sections with no sibling to merge with, e.g. a short clause followed by sub-clauses).",
        "",
    ]
    return "\n".join(lines)


def build_samples(chunks: list[dict[str, Any]], n: int, seed: int) -> str:
    rng = random.Random(seed)
    sample = rng.sample(chunks, min(n, len(chunks)))
    lines = [
        "# Random chunk samples",
        "",
        f"{len(sample)} chunks drawn with seed {seed}. Review: section number, title, section path, "
        "table formatting, and that the text belongs to the section.",
        "",
    ]
    for i, ch in enumerate(sample, 1):
        lines += [
            f"## {i}. `{ch['chunk_id']}`",
            "",
            f"- spec: {ch['spec']} ({ch['release']}, V{ch['version']})",
            f"- section: §{ch['section']}  title: {ch['title']}",
            f"- section_path: {ch['section_path']}",
            f"- merged_sections: {ch['merged_sections'] or '-'}",
            f"- type: {ch['chunk_type']}  part: {ch['part']}  tokens: {ch['n_tokens']}",
            "",
            "```text",
            ch["text_for_index"],
            "```",
            "",
        ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    cfg = load_config()
    parser = argparse.ArgumentParser(description="Chunk statistics and random samples")
    parser.add_argument("--n", type=int, default=10, help="number of random chunks")
    parser.add_argument("--seed", type=int, default=cfg["seed"])
    args = parser.parse_args(argv)

    chunks = load_chunks(resolve_path(cfg["paths"]["chunks_file"]))
    results = resolve_path(cfg["paths"]["results_dir"])
    results.mkdir(parents=True, exist_ok=True)

    stats = build_stats(chunks, cfg)
    samples = build_samples(chunks, args.n, args.seed)
    (results / "chunk_stats.md").write_text(stats, encoding="utf-8")
    (results / "chunk_samples.md").write_text(samples, encoding="utf-8")

    sys.stdout.reconfigure(encoding="utf-8")
    print(stats)
    print(samples)
    print(f"Wrote {results / 'chunk_stats.md'} and {results / 'chunk_samples.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
