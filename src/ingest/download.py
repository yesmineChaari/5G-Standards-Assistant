"""Corpus constitution: download the 3GPP specs, unzip them and document them in CORPUS.md.

Usage:
    python -m src.ingest.download [--force]

For every spec listed in ``config.yaml`` (``corpus.specs``) this module:
  1. downloads ``<url><file>`` into ``data/raw/`` (skipped if the zip is already there),
  2. extracts the ``.docx`` from the zip,
  3. computes the SHA256 of the zip,
  4. rewrites the auto-generated table in ``CORPUS.md``.

If the 3GPP server cannot be reached, manual download instructions are printed.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import logging
import sys
import zipfile
from pathlib import Path
from typing import Any

import requests

from src.config import load_config, resolve_path

logger = logging.getLogger(__name__)

MANIFEST_NAME = "manifest.json"
AUTO_START = "<!-- AUTO-GENERATED:START (src/ingest/download.py) -->"
AUTO_END = "<!-- AUTO-GENERATED:END -->"
HTTP_TIMEOUT = 60
CHUNK_SIZE = 1 << 16


class DownloadError(RuntimeError):
    """Raised when a spec archive cannot be downloaded."""


def sha256_of(path: Path) -> str:
    """Return the hex SHA256 digest of a file."""
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(CHUNK_SIZE), b""):
            digest.update(block)
    return digest.hexdigest()


def download_file(url: str, dest: Path) -> None:
    """Stream ``url`` to ``dest`` (written atomically through a ``.part`` file)."""
    tmp = dest.with_suffix(dest.suffix + ".part")
    try:
        with requests.get(url, stream=True, timeout=HTTP_TIMEOUT) as resp:
            resp.raise_for_status()
            with open(tmp, "wb") as fh:
                for block in resp.iter_content(CHUNK_SIZE):
                    fh.write(block)
    except requests.RequestException as exc:
        tmp.unlink(missing_ok=True)
        raise DownloadError(f"Could not download {url}: {exc}") from exc
    tmp.replace(dest)


def extract_docx(zip_path: Path, out_dir: Path) -> Path:
    """Extract the single ``.docx`` contained in ``zip_path`` and return its path."""
    with zipfile.ZipFile(zip_path) as zf:
        docx_names = [n for n in zf.namelist() if n.lower().endswith(".docx")]
        if not docx_names:
            raise DownloadError(f"No .docx found in {zip_path.name}: {zf.namelist()}")
        if len(docx_names) > 1:
            logger.warning("Several .docx in %s, using %s", zip_path.name, docx_names[0])
        name = docx_names[0]
        target = out_dir / Path(name).name
        if not target.exists() or target.stat().st_size != zf.getinfo(name).file_size:
            with zf.open(name) as src, open(target, "wb") as dst:
                dst.write(src.read())
    return target


def _load_manifest(raw_dir: Path) -> dict[str, Any]:
    path = raw_dir / MANIFEST_NAME
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def _save_manifest(raw_dir: Path, manifest: dict[str, Any]) -> None:
    (raw_dir / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2), encoding="utf-8")


def fetch_spec(spec: dict[str, Any], raw_dir: Path, force: bool = False) -> dict[str, Any]:
    """Download (if needed) and unzip one spec. Returns its corpus record."""
    zip_path = raw_dir / spec["file"]
    url = spec["url"].rstrip("/") + "/" + spec["file"]
    downloaded_now = False
    if force or not zip_path.exists():
        logger.info("Downloading %s", url)
        download_file(url, zip_path)
        downloaded_now = True
    else:
        logger.info("Already present: %s", zip_path.name)

    docx_path = extract_docx(zip_path, raw_dir)
    return {
        "spec": spec["id"],
        "title": spec.get("title", ""),
        "version": spec["version"],
        "release": spec["release"],
        "url": url,
        "file": spec["file"],
        "docx": docx_path.name,
        "sha256": sha256_of(zip_path),
        "downloaded_now": downloaded_now,
        "mtime_date": dt.date.fromtimestamp(zip_path.stat().st_mtime).isoformat(),
    }


def render_table(records: list[dict[str, Any]]) -> str:
    """Render the auto-generated corpus table in Markdown."""
    lines = [
        "| Spec | Title | Version | Release | URL | Zip file | Extracted .docx | SHA256 (zip) | Download date |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in records:
        lines.append(
            f"| {r['spec']} | {r['title']} | V{r['version']} | {r['release']} | {r['url']} "
            f"| `{r['file']}` | `{r['docx']}` | `{r['sha256']}` | {r['download_date']} |"
        )
    return "\n".join(lines)


CORPUS_TEMPLATE = f"""# Corpus

The chatbot answers only from the two 3GPP Release 18 specifications below.

## Files

{AUTO_START}
{AUTO_END}

The table above is regenerated by `make download` (`src/ingest/download.py`).
The SHA256 lets anyone check that they use exactly the same files.

## Why these two specifications

- **TS 23.501 (Stage 2)** describes the architecture of the 5G System: network functions
  (AMF, SMF, UPF, NRF, PCF, ...), reference points, mobility, sessions, QoS and network slicing.
  It explains *what* each procedure is for and *which* entities take part.
- **TS 24.501 (Stage 3)** specifies the NAS protocol between the UE and the network: 5GMM and
  5GSM procedures, message contents, information elements, timers and cause values.
  It defines *exactly how* the procedures are signalled.
- Together they support cross-spec questions, e.g. the registration procedure (architecture
  and role of the AMF in 23.501) and the NAS messages exchanged (REGISTRATION REQUEST / ACCEPT /
  COMPLETE in 24.501).
- Both are normative, written in English, and available in Release 18, so the corpus is coherent.

## Why the .docx and not the PDF

- The .docx is the official format published by 3GPP on its FTP archive.
- Its paragraph **heading styles** (`Heading 1` ... `Heading 9`) give reliable section numbers,
  titles and levels, which are needed for structural chunking and for exact citations
  such as `(TS 24.501, §5.5.1.2.2)`.
- Tables keep their row/cell structure and can be converted to Markdown. PDF extraction loses
  this structure and mixes headers, footers and page numbers into the text.
"""


def update_corpus_md(path: Path, table: str) -> None:
    """Write ``table`` between the auto-generated markers of CORPUS.md (create it if missing)."""
    text = path.read_text(encoding="utf-8") if path.exists() else CORPUS_TEMPLATE
    if AUTO_START not in text or AUTO_END not in text:
        raise ValueError(f"{path} lacks the auto-generated markers; restore them or delete the file")
    head, rest = text.split(AUTO_START, 1)
    _, tail = rest.split(AUTO_END, 1)
    path.write_text(f"{head}{AUTO_START}\n{table}\n{AUTO_END}{tail}", encoding="utf-8")


def manual_instructions(specs: list[dict[str, Any]], raw_dir: Path) -> str:
    """Return instructions for placing the archives manually."""
    lines = [
        "Automatic download failed. Download these files manually with a browser:",
        "",
    ]
    for spec in specs:
        lines.append(f"  - {spec['url'].rstrip('/')}/{spec['file']}")
    lines += [
        "",
        f"and place them (as .zip, do not rename) in: {raw_dir}",
        "Then run `make download` again: it will unzip them, compute SHA256 and update CORPUS.md.",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="re-download even if the zip exists")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    cfg = load_config()
    specs = cfg["corpus"]["specs"]
    raw_dir = resolve_path(cfg["paths"]["raw_dir"])
    raw_dir.mkdir(parents=True, exist_ok=True)

    manifest = _load_manifest(raw_dir)
    records = []
    try:
        for spec in specs:
            rec = fetch_spec(spec, raw_dir, force=args.force)
            prev = manifest.get(rec["file"], {})
            if rec["downloaded_now"] or prev.get("sha256") != rec["sha256"]:
                rec["download_date"] = (
                    dt.date.today().isoformat() if rec["downloaded_now"] else rec["mtime_date"]
                )
            else:
                rec["download_date"] = prev.get("download_date", rec["mtime_date"])
            manifest[rec["file"]] = {"sha256": rec["sha256"], "download_date": rec["download_date"]}
            records.append(rec)
    except DownloadError as exc:
        logger.error("%s", exc)
        print(manual_instructions(specs, raw_dir), file=sys.stderr)
        return 1

    _save_manifest(raw_dir, manifest)
    corpus_md = resolve_path(cfg["paths"]["corpus_doc"])
    update_corpus_md(corpus_md, render_table(records))
    for r in records:
        logger.info("%s V%s -> %s  sha256=%s", r["spec"], r["version"], r["docx"], r["sha256"])
    logger.info("Updated %s", corpus_md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
